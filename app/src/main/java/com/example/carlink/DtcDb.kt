/** კოდის ახსნა; თუ ზუსტი კოდი სიაში არ არის, ვაძლევთ სისტემის ზოგად აღწერას. */
fun dtcText(code: String): String {
    DTC_INFO[code]?.let { return it }
    val c = code.uppercase()
    if (c.length < 5) return "უცნობი კოდი"
    val group = when (c[0]) {
        'P' -> "ძრავა/გადაცემა"
        'C' -> "შასი (მუხრუჭი, მართვა)"
        'B' -> "ძარა (SRS, კომფორტი)"
        'U' -> "ქსელი/კომუნიკაცია"
        else -> "უცნობი"
    }
    val scope = when (c[1]) {
        '0', '2' -> "ზოგადი კოდი (ყველა მწარმოებლისთვის)"
        '1', '3' -> "მწარმოებლის (Chevrolet/GM) საკუთარი კოდი"
        else -> ""
    }
    val sub = if (c[0] == 'P') when (c[2]) {
        '1' -> "საწვავი/ჰაერის გაზომვა"
        '2' -> "საწვავის სისტემა (ინჟექტორები)"
        '3' -> "ანთება / გამოტოვება"
        '4' -> "დამხმარე გამონაბოლქვი"
        '5' -> "სიჩქარე / უქმი სვლა / დამხმარე"
        '6' -> "კომპიუტერი და გამომავალი წრედები"
        '7', '8', '9' -> "გადაცემათა კოლოფი"
        else -> ""
    } else ""
    val parts = listOf(group, sub, scope).filter { it.isNotEmpty() }.joinToString(" · ")
    return "ზუსტი ახსნა ჩემს სიაში არ არის. $parts. მოძებნე კოდით: \"$c Chevrolet Cruze\"."
}
